from pathlib import Path
from uuid import uuid4

from fastapi import HTTPException, UploadFile, status


MAX_DOCUMENT_SIZE = 5 * 1024 * 1024
ALLOWED_EXTENSIONS = {".pdf", ".jpg", ".jpeg", ".png"}
PRIVATE_DOCUMENT_DIR = Path(__file__).resolve().parents[1] / "private_uploads"


def save_private_document(upload: UploadFile) -> str:
    extension = Path(upload.filename or "").suffix.lower()
    if extension not in ALLOWED_EXTENSIONS:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Only PDF, JPG, and PNG documents are accepted",
        )

    content = upload.file.read(MAX_DOCUMENT_SIZE + 1)
    if len(content) > MAX_DOCUMENT_SIZE:
        raise HTTPException(
            status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
            detail="Document must be 5 MB or smaller",
        )

    PRIVATE_DOCUMENT_DIR.mkdir(mode=0o700, parents=True, exist_ok=True)
    stored_name = f"{uuid4().hex}{extension}"
    destination = PRIVATE_DOCUMENT_DIR / stored_name
    destination.write_bytes(content)
    destination.chmod(0o600)
    return stored_name


def private_document_path(stored_name: str) -> Path:
    # Stored names are generated by this module. Resolve defensively to ensure
    # a database value can never escape the private document directory.
    candidate = (PRIVATE_DOCUMENT_DIR / Path(stored_name).name).resolve()
    if candidate.parent != PRIVATE_DOCUMENT_DIR.resolve():
        raise HTTPException(status_code=404, detail="Document not found")
    return candidate
